/**
 * Generates a brand new empty capture card when needed (unlimited cards support!)
 */
export function createNewEmptyCard(nextSlotIndex: number): Mecard {
  return {
    id: `mecard-card-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    slotIndex: nextSlotIndex,
    isEquipped: nextSlotIndex < 3,
    isCaptured: false,
  };
}

